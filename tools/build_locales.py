"""Build the offline browser catalog. No runtime translation service is used."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def build():
    lines = ['// Generated by tools/build_locales.py; edit the JSON catalogs.']
    for file, variable in [('en.json', 'VaMPMEnglish'), ('messages.en.json', 'VaMPMMessagesEnglish')]:
        catalog = json.loads((ROOT / 'web/locales' / file).read_text('utf-8'))
        if not all(isinstance(k, str) and isinstance(v, str) for k, v in catalog.items()):
            raise ValueError('Translation catalogs must map strings to strings')
        lines.append('window.' + variable + '=' + json.dumps(catalog, ensure_ascii=False, separators=(',', ':')) + ';')
    return '\n'.join(lines) + '\n'

if __name__ == '__main__':
    (ROOT / 'web/locales/en.js').write_text(build(), 'utf-8', newline='\n')
