const {test,expect}=require('@playwright/test');
const fs=require('fs');

test('recommendation cards open details, favorite files and create dynamic source profiles',async({page})=>{
  const {url,token}=JSON.parse(fs.readFileSync('test-results/ui-server.json','utf8'));
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const get=async route=>(await page.request.get(url+'/api/'+route,{headers:{'X-Session-Token':token}})).json();
  await page.request.post(url+'/api/settings',{headers:{'X-Session-Token':token},data:{provider:'codex'}});
  await page.goto(url+'/#'+token);
  await page.getByRole('button',{name:'✧ 对话助手'}).click();
  await page.getByRole('button',{name:'新对话',exact:true}).click();
  await page.getByLabel('发送给助手的消息').fill('推荐一个人物包');
  await page.getByRole('button',{name:'发送 ↑'}).click();
  const card=page.locator('.recommendation-card');
  await expect(card).toHaveCount(1);
  await expect(card.locator('.package-art img')).toBeVisible();
  await expect(card.locator('.warning-mark')).toHaveText('!');
  expect(await page.locator('.chat-message.assistant').evaluate(e=>!!(e.compareDocumentPosition(document.querySelector('.recommendation-card'))&Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true);
  await card.getByRole('button',{name:'打开 Luna'}).click();
  await expect(page.locator('#drawer h2')).toHaveText('Luna');
  await expect(page.locator('#drawer')).toContainText('文件大小与发布信息不符');
  await expect(page.locator('#drawer')).toContainText('文件已保留');
  await page.getByRole('button',{name:'关闭详情'}).click();
  await card.getByRole('button',{name:'取消收藏',exact:true}).click();
  await expect(card.getByRole('button',{name:'收藏',exact:true})).toBeVisible();
  expect((await get('package?key=artist.luna.2')).files[0].rel).toBe('人物/Artist.Luna.2.var');
  await card.getByRole('button',{name:'收藏',exact:true}).click();
  await expect(card.getByRole('button',{name:'取消收藏',exact:true})).toBeVisible();
  expect((await get('package?key=artist.luna.2')).files[0].rel).toBe('收藏/人物/Artist.Luna.2.var');
  await page.screenshot({path:'test-results/推荐卡片与收藏.png',fullPage:true});
  await page.locator('#navigation [data-action=favorites]').click();
  await expect(page.getByRole('heading',{name:'收藏夹',exact:true})).toBeVisible();
  await expect(page.locator('.package-row')).toHaveCount(1);
  await expect(page.locator('.package-row .warning-mark')).toHaveText('!');
  await page.getByRole('button',{name:'▷ 启动方案',exact:true}).click();
  await page.locator('[data-action=source-profile]').click();
  await page.locator('#profile-source-form [name=name]').fill('动态收藏测试');
  await page.getByRole('button',{name:'保存动态方案'}).click();
  const favorites=page.locator('.profile').filter({hasText:'动态收藏测试'});
  await expect(favorites).toContainText('动态跟随全部收藏');
  await expect(favorites).toContainText('1 个主包');
  await page.locator('[data-action=source-profile]').click();
  await page.locator('#profile-source').selectOption('folder');
  await page.locator('#profile-folder').fill('收藏/人物');
  await page.locator('#profile-source-form [name=name]').fill('动态目录测试');
  await page.getByRole('button',{name:'保存动态方案'}).click();
  const folder=page.locator('.profile').filter({hasText:'动态目录测试'});
  await expect(folder).toContainText('动态跟随：收藏/人物');
  await folder.getByRole('button',{name:'预览启用',exact:true}).click();
  await expect(page.locator('#dialog')).toContainText('合计启用 1');
  await page.getByRole('button',{name:'取消',exact:true}).click();
  await page.screenshot({path:'test-results/动态收藏启动方案.png',fullPage:true});
  await page.getByRole('button',{name:'✧ 对话助手'}).click();
  await page.getByRole('button',{name:'新对话',exact:true}).click();
  expect(errors).toEqual([]);
});

test('favorites profile refreshes across windows, tracks dependencies and recovers from empty',async({page,context})=>{
  const {url,token}=JSON.parse(fs.readFileSync('test-results/ui-server.json','utf8'));
  const headers={'X-Session-Token':token},errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const get=async route=>(await page.request.get(url+'/api/'+route,{headers})).json();
  const post=async(route,data)=>{
    const response=await page.request.post(url+'/api/'+route,{headers,data});
    expect(response.ok()).toBe(true);
    const result=await response.json();
    if(result.status==='running'){
      await expect.poll(async()=>(await get('job?id='+result.id)).status,{timeout:15000}).toBe('done');
    }
    return result;
  };
  const original=(await get('package-keys?state=favorite')).keys;
  expect(original).not.toContain('studio.gardendance.1');
  await page.goto(url+'/#'+token);
  await page.getByRole('button',{name:'▷ 启动方案',exact:true}).click();
  await page.locator('[data-action=source-profile]').click();
  await page.locator('#profile-source-form [name=name]').fill('自动同步测试');
  await page.getByRole('button',{name:'保存动态方案'}).click();
  const profile=page.locator('.profile').filter({hasText:'自动同步测试'});
  await expect(profile).toContainText('自动更新');
  await expect(profile).toContainText(`${original.length} 个主包`);
  const saved=(await get('profiles')).find(p=>p.name==='自动同步测试');
  await profile.getByRole('button',{name:'复制为固定选择'}).click();
  await expect(page.locator('#toast')).toContainText('固定选择');
  const library=await context.newPage();
  library.on('pageerror',e=>errors.push(e.message));
  await library.goto(url+'/#'+token);await library.locator('#navigation [data-page="library"]').click();
  await library.getByLabel('搜索资源').fill('GardenDance');
  await expect(library.locator('.package-row')).toHaveCount(1);
  await library.getByRole('button',{name:'收藏',exact:true}).click();
  await expect(library.getByRole('button',{name:'取消收藏',exact:true})).toBeVisible();
  // No reload/navigation of the original page: polling observes a star in another window.
  await expect(profile).toContainText(`${original.length+1} 个主包`,{timeout:12000});
  await expect(profile).toContainText(`含依赖 ${saved.included_count+2} 个包`);
  const updated=(await get('profiles')).find(p=>p.id===saved.id);
  expect(updated.keys).toContain('studio.gardendance.1');
  expect(updated.source.type).toBe('favorites');
  expect((await get('package?key=assets.garden.1')).favorite).toBe(false);
  await page.screenshot({path:'test-results/收藏方案自动同步.png',fullPage:true});
  await profile.getByRole('button',{name:'预览启用',exact:true}).click();
  await expect(page.locator('#dialog')).toContainText(`合计启用 ${saved.included_count+2}`);
  await page.getByRole('button',{name:'取消',exact:true}).click();
  await library.close();
  // Agent/API favorite changes use the same state and also reach open profile pages.
  await post('favorite',{keys:updated.keys,favorite:false});
  await expect(profile).toContainText('0 个主包',{timeout:12000});
  await expect(profile.getByRole('button',{name:'预览启用',exact:true})).toBeDisabled();
  await expect(profile).toContainText('新增资源后会自动加入此方案');
  await post('favorite',{keys:original,favorite:true});
  await expect(profile).toContainText(`${original.length} 个主包`,{timeout:12000});
  await expect(profile.getByRole('button',{name:'预览启用',exact:true})).toBeEnabled();
  await page.reload();
  await page.getByRole('button',{name:'▷ 启动方案',exact:true}).click();
  await expect(profile).toContainText(`${original.length} 个主包`);
  expect((await get('profiles')).find(p=>p.id===saved.id).keys.sort()).toEqual(original.sort());
  expect(errors).toEqual([]);
});
