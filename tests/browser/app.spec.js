const {test,expect}=require('@playwright/test');
const fs=require('fs');
const path=require('path');

test('library, search, favorites, profiles, recovery, duplicate cleanup and file import',async({page})=>{
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const {url,token}=JSON.parse(fs.readFileSync('test-results/ui-server.json','utf8'));
  await page.goto(url+'/#'+token);await page.locator('#navigation [data-page="library"]').click();
  await expect(page.getByRole('heading',{name:'资源库',exact:true})).toBeVisible();
  await expect(page.locator('.package-row')).toHaveCount(6);
  await page.screenshot({path:'test-results/界面预览.png',fullPage:true});
  await page.getByLabel('搜索资源').fill('Luna');
  await expect(page.locator('.package-row')).toHaveCount(1);
  await page.getByRole('button',{name:'收藏',exact:true}).click();
  await expect(page.getByRole('button',{name:'取消收藏'})).toBeVisible();
  await page.getByRole('button',{name:'Luna',exact:true}).click();
  await expect(page.locator('#drawer h2')).toHaveText('Luna');
  await page.getByRole('button',{name:'关闭详情'}).click();
  await page.getByLabel('搜索资源').fill('GardenDance');
  await expect(page.locator('.package-row')).toHaveCount(1);
  await page.getByLabel('选择 GardenDance').check();
  await page.getByRole('button',{name:'加入启动方案 →'}).click();
  await page.locator('#profile-name').fill('花园舞蹈');
  await page.getByRole('button',{name:'保存方案',exact:true}).click();
  await expect(page.getByRole('heading',{name:'花园舞蹈'})).toBeVisible();
  await page.getByRole('button',{name:'预览并启用',exact:true}).click();
  await expect(page.locator('#dialog')).toBeVisible();
  await expect(page.locator('#dialog')).toContainText('合计启用 2');
  await page.getByRole('button',{name:'确认执行'}).click();
  await expect(page.locator('#job-panel')).toBeHidden({timeout:15000});
  await page.getByRole('button',{name:'↶ 操作记录'}).click();
  const activated=page.locator('.operation').filter({hasText:'切换按需启用方案'});
  await activated.getByRole('button',{name:'恢复此操作'}).click();
  await expect(activated.locator('.badge')).toHaveText('已恢复',{timeout:15000});
  await page.getByRole('button',{name:'▱ 重复清理'}).click();
  await page.getByRole('button',{name:'开始内容校验'}).click();
  await expect(page.getByRole('heading',{name:'校验结果'})).toBeVisible({timeout:15000});
  await page.getByRole('button',{name:'预览清理'}).click();
  await expect(page.locator('#dialog')).toContainText('计划移动 1 个');
  await page.getByRole('button',{name:'确认执行'}).click();
  await expect(page.locator('#job-panel')).toBeHidden({timeout:15000});
  await page.getByRole('button',{name:'⛓ 依赖检查'}).click();
  await expect(page.getByRole('cell',{name:'Absent.Light.2 Demo.NeedDependency.1'})).toBeVisible();
  await page.getByRole('button',{name:/⊞资源库|⊞ 资源库/}).click();
  await page.getByRole('button',{name:'＋ 添加资源'}).click();
  await page.locator('#import-files').setInputFiles('test-results/Import.NewHair.1.var');
  await page.locator('#import-ai').uncheck();
  await page.locator('#import-find').uncheck();
  await page.getByRole('button',{name:'导入并分析'}).click();
  await expect(page.getByRole('heading',{name:'资源导入完成'})).toBeVisible({timeout:15000});
  await expect(page.locator('#dialog')).toContainText('成功 1 个');
  await page.getByRole('button',{name:'完成',exact:true}).click();
  await page.getByLabel('搜索资源').fill('NewHair');
  await expect(page.getByRole('button',{name:'NewHair',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'⚙ AI 与设置'}).click();
  await page.locator('#ai-provider').selectOption('deepseek');
  await expect(page.locator('input[name=base_url]')).toBeVisible();
  await page.getByRole('button',{name:'保存设置'}).click();
  await expect(page.locator('#ai-provider')).toHaveValue('deepseek');
  await page.setViewportSize({width:760,height:900});
  await page.screenshot({path:'test-results/窄屏预览.png',fullPage:true});
  expect(errors).toEqual([]);
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  expect(overflow).toBe(false);
});
