const {test,expect}=require('@playwright/test');
const fs=require('fs');
const connection=()=>JSON.parse(fs.readFileSync('test-results/ui-server.json','utf8'));
async function chat(page){const {url,token}=connection();await page.goto(url+'/#'+token);await page.getByRole('button',{name:'✧ 对话助手',exact:true}).click();}

test('preset shortcuts fill only, featured selection and CRUD persist across pages',async({page,browser,request})=>{
  const {url,token}=connection(),headers={'X-Session-Token':token},errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const get=async path=>(await(await request.get(url+'/api/'+path,{headers})).json());
  const before=await get('agent/state');
  await chat(page);
  const bar=page.locator('.chat-preset-shortcuts');await expect(bar.getByRole('button')).toHaveCount(5);
  await bar.getByRole('button',{name:'推荐人物卡',exact:true}).click();
  expect(await page.getByLabel('发送给助手的消息').inputValue()).toContain('人物外观包');
  expect((await get('agent/state')).messages).toEqual(before.messages);
  await page.getByRole('button',{name:'查看全部对话预设'}).click();
  const dialog=page.locator('#preset-dialog');await expect(dialog).toBeVisible();
  await expect(dialog.locator('.preset-row')).toHaveCount(10);
  const duplicate=dialog.locator('.preset-row').filter({has:page.getByText('检查重复包',{exact:true})});
  await expect(duplicate.getByRole('checkbox')).toBeDisabled();
  await duplicate.locator('.preset-use').click();
  await expect(dialog).not.toBeVisible();await expect(page.getByLabel('发送给助手的消息')).toHaveValue('帮我检查资源库里的重复包，先给我清理方案，不执行。');
  await page.getByRole('button',{name:'查看全部对话预设'}).click();
  await dialog.getByLabel('常用：推荐人物卡',{exact:true}).uncheck();
  await dialog.getByRole('button',{name:'＋ 新增预设',exact:true}).click();
  await dialog.getByLabel('标题',{exact:true}).fill('我的人物推荐');
  await dialog.getByLabel('提示词',{exact:true}).fill('只从收藏推荐三个自然风格人物。');
  await dialog.getByLabel('显示在常用栏',{exact:true}).check();
  await dialog.getByRole('button',{name:'保存预设',exact:true}).click();
  await expect(dialog.locator('.preset-row')).toHaveCount(11);
  await dialog.getByRole('button',{name:'关闭预设面板'}).click();
  await expect(bar.getByRole('button')).toHaveCount(5);
  await expect(bar.getByRole('button',{name:'我的人物推荐',exact:true})).toBeVisible();
  const context=await browser.newContext(),fresh=await context.newPage();
  await chat(fresh);await expect(fresh.locator('.chat-preset-shortcuts').getByRole('button',{name:'我的人物推荐',exact:true})).toBeVisible();await context.close();
  await page.getByRole('button',{name:'查看全部对话预设'}).click();
  const custom=dialog.locator('.preset-row').filter({hasText:'我的人物推荐'});
  await custom.getByRole('button',{name:'编辑',exact:true}).click();
  await dialog.getByLabel('标题',{exact:true}).fill('精选人物');
  await dialog.getByLabel('提示词',{exact:true}).fill('人物 <script>window.presetUnsafe=1</script> 与服饰，保留特殊符号。');
  await dialog.getByRole('button',{name:'保存预设',exact:true}).click();
  await expect(dialog.locator('.preset-row').filter({hasText:'精选人物'})).toBeVisible();
  expect(await page.evaluate(()=>window.presetUnsafe)).toBeUndefined();
  await page.screenshot({path:'test-results/对话预设-全部与常用.png'});
  const edited=dialog.locator('.preset-row').filter({hasText:'精选人物'});
  await edited.getByRole('button',{name:'删除',exact:true}).click();
  await edited.getByRole('button',{name:'确认删除',exact:true}).click();
  await expect(dialog.locator('.preset-row')).toHaveCount(10);
  await dialog.getByLabel('常用：推荐人物卡',{exact:true}).check();
  await page.setViewportSize({width:390,height:700});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await expect(dialog.getByRole('button',{name:'＋ 新增预设',exact:true})).toBeInViewport();
  await page.screenshot({path:'test-results/对话预设-窄窗口.png'});
  await dialog.getByRole('button',{name:'关闭预设面板'}).click();
  await expect(page.getByRole('button',{name:'查看全部对话预设'})).toBeInViewport();
  expect(errors).toEqual([]);
});

test('AI drafts use the saved chat model, stay editable and survive failure or cancellation',async({page,request})=>{
  const {url,token}=connection(),headers={'X-Session-Token':token};
  const get=async path=>(await(await request.get(url+'/api/'+path,{headers})).json());
  const post=async(path,data)=>(await(await request.post(url+'/api/'+path,{headers,data})).json());
  const settings=await get('settings'),before=await get('chat-presets'),conversation=await get('agent/state');
  try{
    await post('settings',{provider:'compatible',api_model:'chat-fixture',api_summary_model:'summary-fixture'});
    await chat(page);await page.getByLabel('发送给助手的消息').fill('我的聊天草稿');
    await page.getByRole('button',{name:'查看全部对话预设'}).click();
    const dialog=page.locator('#preset-dialog');
    await dialog.getByRole('button',{name:'＋ 新增预设',exact:true}).click();
    const title=dialog.getByLabel('标题',{exact:true}),prompt=dialog.getByLabel('提示词',{exact:true});
    await title.fill('推荐清爽服装');await prompt.fill('保留原内容');
    await dialog.getByRole('button',{name:'✧ AI 生成提示词',exact:true}).click();
    await expect(dialog.locator('.preset-draft-status')).toContainText('已生成 · chat-fixture',{timeout:15000});
    expect(await prompt.inputValue()).toContain('推荐清爽服装');
    expect(await get('chat-presets')).toEqual(before);expect((await get('agent/state')).messages).toEqual(conversation.messages);
    await expect(page.getByLabel('发送给助手的消息')).toHaveValue('我的聊天草稿');
    await page.screenshot({path:'test-results/对话预设-AI编辑.png'});
    await title.fill('生成失败');await prompt.fill('失败时保留的内容');
    await dialog.getByRole('button',{name:'✧ AI 生成提示词',exact:true}).click();
    await expect(dialog.locator('.preset-draft-status')).toContainText('模拟接口错误',{timeout:15000});
    await expect(prompt).toHaveValue('失败时保留的内容');
    await title.fill('正在取消');
    const started=page.waitForResponse(r=>r.url().endsWith('/api/chat-presets/draft'));
    await dialog.getByRole('button',{name:'✧ AI 生成提示词',exact:true}).click();await started;
    await dialog.getByRole('button',{name:'停止生成',exact:true}).click();
    await expect(prompt).toHaveValue('失败时保留的内容');
    await expect.poll(async()=>(await get('status')).busy).toBe(false);
    await expect(dialog.locator('.preset-draft-status')).toContainText('已停止生成');
    await title.fill('关闭时取消');
    const closing=page.waitForResponse(r=>r.url().endsWith('/api/chat-presets/draft'));
    await dialog.getByRole('button',{name:'✧ AI 生成提示词',exact:true}).click();await closing;
    await page.keyboard.press('Escape');await expect(dialog).not.toBeVisible();
    await expect.poll(async()=>(await get('status')).busy).toBe(false);
    await page.getByRole('button',{name:'查看全部对话预设'}).click();
    await dialog.getByRole('button',{name:'＋ 新增预设',exact:true}).click();
    await expect(prompt).toHaveValue('');expect(await get('chat-presets')).toEqual(before);
  }finally{await post('settings',{provider:settings.provider,api_model:settings.api_model,api_summary_model:settings.api_summary_model});}
});
