const {test,expect}=require('@playwright/test');
const fs=require('fs');

test('separate tags preserve summary, use counts, show all in details and stay searchable',async({page})=>{
  const {url,token}=JSON.parse(fs.readFileSync('test-results/ui-server.json','utf8'));
  const headers={'X-Session-Token':token},errors=[];page.on('pageerror',e=>errors.push(e.message));
  const get=async route=>(await page.request.get(url+'/api/'+route,{headers})).json();
  const post=async(route,data)=>{const r=await page.request.post(url+'/api/'+route,{headers,data});expect(r.ok()).toBeTruthy();return r.json();};
  await post('label',{key:'artist.luna.2',summary:'原简介保持不变',tags:[]});
  await page.goto(url+'/#'+token);await page.locator('#navigation [data-page="library"]').click();
  await page.getByLabel('搜索资源').fill('Artist.Luna');
  await expect(page.locator('.package-row')).toHaveCount(1);
  await page.locator('.package-row').click();
  await page.locator('[data-action=detail-ai]').click();
  const dialog=page.locator('#dialog');
  await expect(dialog.locator('input[name=summary-target][value=both]')).toBeChecked();
  await dialog.locator('input[name=summary-target][value=tags]').check();
  await dialog.getByRole('button',{name:'确认开始',exact:true}).click();
  await expect.poll(async()=>(await get('status')).summary_queue.status).toBe('done');
  const p=await get('package?key=artist.luna.2');
  expect(p.summary).toBe('原简介保持不变');expect(p.tags_generated).toBe(true);expect(p.tags.length).toBe(6);
  await page.reload();await page.locator('#navigation [data-page="library"]').click();
  const closeNotice=page.getByRole('button',{name:'关闭生成完成提示',exact:true});
  await expect(page.locator('#summary-queue')).toContainText('仅标签');
  await page.setViewportSize({width:420,height:844});
  const panelBox=await page.locator('.summary-queue-card').boundingBox(),closeBox=await closeNotice.boundingBox();
  expect(closeBox.x+closeBox.width).toBeLessThanOrEqual(panelBox.x+panelBox.width);
  expect(closeBox.x+closeBox.width).toBeGreaterThan(panelBox.x+panelBox.width-20);
  expect(closeBox.y-panelBox.y).toBeLessThan(16);
  await page.screenshot({path:'test-results/生成完成提示-关闭按钮.png'});
  await closeNotice.focus();await page.keyboard.press('Enter');
  await expect(page.locator('.summary-queue-card')).toHaveCount(0);
  expect((await get('package?key=artist.luna.2')).tags).toEqual(p.tags);
  await page.setViewportSize({width:1440,height:1000});
  await page.getByLabel('搜索资源').fill('Artist.Luna');
  await page.getByRole('button',{name:'⊞ 大图',exact:true}).click();
  const card=page.locator('.package-row');
  await expect(card.locator('.content-tag')).toHaveCount(3);
  await expect(card.locator('.tags-more')).toHaveText('+3');
  await expect(card.locator('[data-tags-toggle]')).toHaveCount(0);
  await page.getByLabel('搜索资源').fill('精灵耳');
  await expect(card).toHaveCount(1);
  await page.screenshot({path:'test-results/内容标签-资源卡片.png'});
  await card.locator('.tags-more').click();
  await expect(page.locator('#drawer .content-tag:visible')).toHaveCount(6);
  await expect(page.locator('#drawer .content-tags')).toContainText('精灵耳');
  await expect(page.locator('#drawer .tags-more,#drawer [data-tags-toggle]')).toHaveCount(0);
  await page.locator('#drawer details').filter({hasText:'编辑分类、简介与标签'}).locator('summary').click();
  await page.locator('#label-form [name=tags]').fill('银白发，长发，自定义标签');
  await page.locator('#label-form button[type=submit]').click();
  await expect.poll(async()=>(await get('package?key=artist.luna.2')).tags).toEqual(['银白发','长发','自定义标签']);
  await page.locator('[data-action=close-drawer]').click();
  await page.locator('#navigation [data-page=assistant]').click();
  await page.locator('#chat-input').fill('推荐 Luna 人物');await page.locator('#chat-form button[type=submit]').click();
  await expect(page.locator('.recommendation-card .content-tag')).toHaveCount(3);
  await expect(page.locator('.recommendation-card .tags-more')).toHaveCount(0);
  expect(await page.locator('.recommendation-card').evaluate(card=>
    card.querySelector('.category-badges').getBoundingClientRect().top>=card.querySelector('.recommendation-name').getBoundingClientRect().bottom)).toBe(true);
  await page.screenshot({path:'test-results/内容标签-助手推荐.png'});
  expect(errors).toEqual([]);
});
