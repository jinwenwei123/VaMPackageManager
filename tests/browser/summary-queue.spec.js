const {test,expect}=require('@playwright/test');
const fs=require('fs');

test('one-click summaries pause, survive refresh, skip saved labels and show separate category tags',async({page})=>{
  const {url,token}=JSON.parse(fs.readFileSync('test-results/ui-server.json','utf8'));
  const headers={'X-Session-Token':token},errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const get=async route=>(await page.request.get(url+'/api/'+route,{headers})).json();
  const post=async(route,data)=>{
    const r=await page.request.post(url+'/api/'+route,{headers,data});expect(r.ok()).toBe(true);
    const out=await r.json();
    if(out.id)await expect.poll(async()=>(await get('job?id='+out.id)).status,{timeout:15000}).toBe('done');
    return out;
  };
  const ids=[],keys=Array.from({length:24},(_,i)=>`aiqueue.look${String(i).padStart(2,'0')}.1`);
  for(let i=0;i<24;i++){
    const name=`AIQueue.Look${String(i).padStart(2,'0')}.1.var`;
    const r=await page.request.post(url+'/api/upload?name='+name,{headers:{...headers,'Content-Type':'application/octet-stream'},data:fs.readFileSync('test-results/'+name)});
    expect(r.ok()).toBe(true);ids.push((await r.json()).id);
  }
  await post('import',{ids,ai:false,find:false});
  await post('favorite',{keys:keys.slice(0,23),favorite:true});
  await post('label',{key:keys[22],category:'服饰',summary:'我的手动简介保留'});
  await page.goto(url+'/#'+token);await page.locator('#navigation [data-page="library"]').click();
  await page.getByRole('button',{name:'☷ 列表',exact:true}).click();
  const oneClick=page.getByRole('button',{name:'✧ 一键 AI 简介',exact:true});
  await expect(oneClick).toBeVisible();
  await page.locator('#navigation [data-action=favorites]').click();
  await expect(page.getByRole('heading',{name:'收藏夹',exact:true})).toBeVisible();
  await page.getByLabel('搜索资源').fill('AIQueue.Look00');
  await expect(page.locator('.package-row')).toHaveCount(1);
  await expect(page.locator('.package-row>.category-badges>.package-category')).toHaveText('▧场景');
  await expect(page.locator('.package-meta')).not.toContainText('场景');
  await expect(oneClick).toBeVisible();
  await oneClick.click();
  const dialog=page.locator('#dialog');
  await expect(dialog.locator('input[value=all]')).toBeChecked();
  await expect(dialog).toContainText('不受搜索、分类或当前页筛选影响');
  await dialog.locator('input[value=missing]').check();
  await dialog.getByRole('button',{name:'确认开始',exact:true}).click();
  await page.locator('#summary-queue [data-action=pause-summary]').click();
  await expect.poll(async()=>(await get('status')).summary_queue.status,{timeout:15000}).toBe('paused');
  await expect(page.getByRole('button',{name:'关闭生成完成提示',exact:true})).toHaveCount(0);
  const paused=(await get('status')).summary_queue;
  expect(paused.scope).toBe('favorites');expect(paused.mode).toBe('missing');expect(paused.total).toBeGreaterThan(10);
  expect(paused.current).toBe(10);
  expect((await get('package?key='+keys[23])).source).toBe('rules');
  await page.reload();await page.locator('#navigation [data-page="library"]').click();
  await expect(page.locator('#summary-queue')).toContainText('已暂停');
  await expect(oneClick).toBeDisabled();
  await page.locator('#navigation [data-action=favorites]').click();
  await page.getByLabel('搜索资源').fill('AIQueue');
  await expect(page.locator('.package-row')).toHaveCount(23);
  await expect(page.getByRole('heading',{name:'收藏夹',exact:true})).toBeVisible();
  await page.screenshot({path:'test-results/一键AI简介-列表暂停.png',fullPage:false});
  await page.locator('#summary-queue [data-action=resume-summary]').click();
  await expect.poll(async()=>(await get('status')).summary_queue.status,{timeout:25000}).toBe('done');
  await expect(page.locator('#summary-queue')).toContainText('本轮完成');
  const completed=(await get('package?key='+keys[0])).summary;
  expect((await get('package?key='+keys[22])).summary).toBe('我的手动简介保留');
  expect((await get('package?key='+keys[23])).source).toBe('rules');
  await page.getByRole('button',{name:'⊞ 大图',exact:true}).click();
  await expect(page.locator('.package-list')).toHaveClass(/grid-view/);
  await expect(page.locator('.package-row .package-info>.category-badges>.package-category').first()).toHaveText('♙人物');
  expect(await page.locator('.package-row .package-info>.category-badges').first().evaluate(el=>getComputedStyle(el).position)).toBe('static');
  await page.screenshot({path:'test-results/一键AI简介-大图分类.png',fullPage:false});
  const finishedQueue=(await get('status')).summary_queue;
  await page.getByRole('button',{name:'关闭生成完成提示',exact:true}).click();
  await expect(page.locator('.summary-queue-card')).toHaveCount(0);
  // Polling, view changes and reload must not resurrect a dismissed completion.
  await page.waitForResponse(r=>r.url()===url+'/api/status');
  await page.getByRole('button',{name:'☷ 列表',exact:true}).click();
  await expect(page.locator('.summary-queue-card')).toHaveCount(0);
  await page.reload();await page.locator('#navigation [data-page="library"]').click();
  await expect(oneClick).toBeVisible();
  await expect(page.locator('.summary-queue-card')).toHaveCount(0);
  const dismissedQueue=(await get('status')).summary_queue;
  expect(dismissedQueue).toMatchObject({...finishedQueue,modified:expect.any(String),notice_dismissed:true});
  expect((await get('package?key='+keys[0])).summary).toBe(completed);
  await page.locator('#navigation [data-action=favorites]').click();
  await expect(oneClick).toBeEnabled();
  await oneClick.click();
  await expect(dialog.locator('input[value=all]')).toBeChecked();
  await dialog.locator('input[value=missing]').check();
  await dialog.getByRole('button',{name:'确认开始',exact:true}).click();
  await expect.poll(async()=>(await get('status')).summary_queue.updated).toBe(0);
  await expect.poll(async()=>(await get('status')).summary_queue.status).toBe('done');
  await expect(page.locator('#summary-queue')).toContainText('本轮完成');
  await expect(page.getByRole('button',{name:'关闭生成完成提示',exact:true})).toBeVisible();
  expect((await get('status')).summary_queue.run_id).not.toBe(finishedQueue.run_id);
  expect((await get('package?key='+keys[0])).summary).toBe(completed);
  await page.locator('#navigation [data-page=library]').click();
  await expect(page.getByRole('heading',{name:'资源库',exact:true})).toBeVisible();
  await expect(oneClick).toBeEnabled();
  await oneClick.click();
  await expect(dialog.locator('input[value=all]')).toBeChecked();
  await dialog.locator('input[value=missing]').check();
  await dialog.getByRole('button',{name:'确认开始',exact:true}).click();
  await expect.poll(async()=>(await get('status')).summary_queue.status,{timeout:15000}).toBe('done');
  expect((await get('package?key='+keys[23])).source).toBe('ai');
  // Opening and cancelling is read-only; default all mode requires explicit confirmation.
  const before=(await get('status')).summary_queue;
  await oneClick.click();await expect(dialog.locator('input[value=all]')).toBeChecked();
  await expect(dialog).toContainText('仅标签不改变已有简介和分类');
  await page.setViewportSize({width:420,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/一键AI简介-模式选择.png'});
  await dialog.getByRole('button',{name:'取消',exact:true}).click();
  expect((await get('status')).summary_queue).toEqual(before);
  await page.setViewportSize({width:1440,height:1000});
  await oneClick.click();
  const started=page.waitForRequest(r=>r.url()===url+'/api/ai-queue/start'&&r.method()==='POST');
  await dialog.getByRole('button',{name:'确认开始',exact:true}).click();
  expect((await started).postDataJSON()).toEqual({scope:'all',mode:'all',target:'both'});
  await expect.poll(async()=>(await get('status')).summary_queue.status,{timeout:40000}).toBe('done');
  expect((await get('status')).summary_queue.updated).toBeGreaterThan(24);
  expect((await get('package?key='+keys[22])).summary).not.toBe('我的手动简介保留');
  expect((await get('package?key='+keys[22])).summary_generated).toBe(true);
  await page.setViewportSize({width:760,height:900});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  expect(errors).toEqual([]);
});
